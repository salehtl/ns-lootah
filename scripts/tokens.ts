// Generate src/styles/tokens.css from the DTCG token file.
// Run with `bun run tokens` after editing src/styles/site.tokens.json.
// Token paths become custom properties by joining with "-": color.primary -> --color-primary.
// Composite typography tokens are skipped; their parts are emitted individually.

const SRC = new URL("../src/styles/site.tokens.json", import.meta.url);
const OUT = new URL("../src/styles/tokens.css", import.meta.url);

type Json = Record<string, any>;
const doc: Json = await Bun.file(SRC).json();
const lines: string[] = [];

const varName = (path: string[]) => `--${path.join("-")}`;
const ref = (v: unknown) =>
  typeof v === "string" && /^\{[^{}]+\}$/.test(v) ? `var(${varName(v.slice(1, -1).split("."))})` : null;

function value(type: string, v: any): string | null {
  const r = ref(v);
  if (r) return r;
  switch (type) {
    case "color":
      // Translucent colours (an alpha below 1) need rgb(); hex carries no alpha in DTCG.
      if (typeof v.alpha === "number" && v.alpha < 1) {
        const [r, g, b] = v.components.map((c: number) => Math.round(c * 255));
        return `rgb(${r} ${g} ${b} / ${v.alpha})`;
      }
      return v.hex ?? `color(srgb ${v.components.join(" ")})`;
    case "dimension":
    case "duration":
      return `${v.value}${v.unit}`;
    case "fontFamily":
      return (Array.isArray(v) ? v : [v])
        .map((f: string) => (/^[a-z-]+$/.test(f) ? f : `"${f}"`))
        .join(", ");
    case "fontWeight":
    case "number":
      return String(v);
    case "cubicBezier":
      return `cubic-bezier(${v.join(", ")})`;
    case "border":
      return `${value("dimension", v.width)} ${v.style} ${value("color", v.color)}`;
    case "transition":
      return `${value("duration", v.duration)} ${value("cubicBezier", v.timingFunction)} ${value("duration", v.delay)}`;
    default:
      return null; // typography and anything else without a single CSS value
  }
}

function walk(node: Json, path: string[], inherited?: string) {
  const type = node.$type ?? inherited;
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith("$") || typeof child !== "object") continue;
    const p = [...path, key];
    if ("$value" in child) {
      const v = value(child.$type ?? type, child.$value);
      if (v !== null) lines.push(`  ${varName(p)}: ${v};`);
    } else {
      walk(child, p, type);
    }
  }
}

walk(doc, []);
await Bun.write(
  OUT,
  `/* Generated by scripts/tokens.ts from site.tokens.json. Do not edit by hand. */\n:root {\n${lines.join("\n")}\n}\n`,
);
console.log(`wrote ${lines.length} custom properties to src/styles/tokens.css`);
